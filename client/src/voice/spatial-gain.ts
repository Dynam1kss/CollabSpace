// гучність від відстані між стільцями. Відстань — у координатах дошки, тому
// від зуму не залежить взагалі: хто як наблизив полотно, на звук не впливає
//
// до FULL_RANGE чути на повну — це «за одним столом». Стікер 160×120, тож
// 220 одиниць ≈ півтора стікери: люди поруч, але не в одній точці
export const FULL_RANGE = 220;

// далі CUTOFF не чути зовсім. Вибрав саме тишу, а не «дуже тихо»: у mesh до
// шести учасників постійний ледь чутний фон з усіх кінців дошки
// перетворюється на кашу, і сенс просторового звуку — можливість відійти й
// поговорити окремо — зникає. 1400 одиниць ≈ девʼять стікерів, тобто
// «на іншому кінці дошки»
export const CUTOFF = 1400;

// між ними — закон оберненої відстані (як у точкового джерела звуку в
// реальності), помножений на лінійне згасання до нуля на самій межі. Без
// цього множника на CUTOFF гучність стрибала б з ~0.16 одразу в нуль, і
// перехід було б чути як клац
export function spatialGain(distance: number) {
  // NaN — це «місця ще не знаю»; краще чути людину, ніж мовчки її заглушити.
  // Нескінченність такої поблажки не потребує: вона просто дуже далеко
  if (Number.isNaN(distance)) return 1;
  if (distance <= FULL_RANGE) return 1;
  if (distance >= CUTOFF) return 0;
  const inverse = FULL_RANGE / distance;
  const fade = 1 - (distance - FULL_RANGE) / (CUTOFF - FULL_RANGE);
  return inverse * fade;
}

export function seatDistance(a: { x: number; y: number }, b: { x: number; y: number }) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
