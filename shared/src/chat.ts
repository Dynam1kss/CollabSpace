// текстовий чат дошки. На відміну від присутності (курсори, виділення,
// замки, вікно), це не ефемерний стан: повідомлення лягають у базу, і хто
// відкриє дошку завтра, побачить розмову, а не порожнечу
export interface ChatMessageInfo {
  id: string;
  // автор — щоб узяти той самий колір, що в його курсора й кружечка
  authorId: string;
  displayName: string;
  text: string;
  createdAt: string;
}

// клієнт → серверу: лише текст. Автора сервер бере з сокета, а не з тіла —
// інакше можна було б підписатись чужим імʼям
export interface ChatSendMessage {
  text: string;
}

export interface ChatHistoryResponse {
  messages: ChatMessageInfo[];
}

// довше сервер не приймає — щоб зіпсований чи зловмисний клієнт не залив
// базу одним повідомленням. Клієнт ставить той самий maxLength на поле
export const CHAT_MAX_LENGTH = 2000;

// скільки останніх повідомлень віддає історія. Посторінкової догрузки поки
// нема: для дошки на кілька людей цього з запасом, а як знадобиться —
// додається курсором по createdAt
export const CHAT_HISTORY_LIMIT = 200;
