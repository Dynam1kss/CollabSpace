// [clientId:u32][x:f32][y:f32] — координати дошки, не екрана: у кожного свій
// зсув і масштаб, тому переводить їх той, хто малює
export const CURSOR_BYTES = 12;

// id сокета, не користувача: та сама людина з двох вкладок — два записи,
// і кожен зникає окремо
export interface PresenceMember {
  clientId: number;
  userId: string;
  displayName: string;
  role: 'OWNER' | BoardRole;
  // потрібне, щоб панель голосу застосовувала ту саму ієрархію, що й сервер
  roleGrantedBy: string | null;
  // чи людина вже в голосовій розмові на момент, коли я зайшов на дошку.
  // Далі це живе окремим кадром VOICE_STATE, а тут — лише початковий знімок
  inVoice: boolean;
  // примусово вимкнені адміністратором — теж знімок на момент входу
  forcedMute: boolean;
  forcedDeafen: boolean;
}

// кого саме примусово вимкнули. userId, а не clientId: вкладок може бути
// кілька, а заборона одна на людину
export interface ForceVoiceMessage {
  userId: string;
  on: boolean;
}

export interface RosterMessage {
  // який із members — це я; себе в списку присутніх не показуємо
  you: number;
  members: PresenceMember[];
}

export interface LeaveMessage {
  clientId: number;
}

// що зараз видно на екрані в того, хто зайшов з телефона — прямокутник у
// координатах дошки. Курсор там марний: пальцем не наводять на точку, а
// возять полотном, і вістря спалахувало б лише в мить тапу. Кадр рідкий,
// як виділення (пан — рух грубий), тому json, а не байти
export interface ViewportMessage {
  x: number;
  y: number;
  width: number;
  height: number;
}

// що в мене посеред екрана: точка в координатах ДОШКИ плюс масштаб.
// Саме точка, а не viewport.x/y — ті рахуються від краю мого вікна, і
// приміряти їх до чужого екрана не можна. Свій розмір екрана теж не шлемо:
// кожен ставить цю точку в центр СВОГО вікна
export interface ShowViewMessage {
  centerX: number;
  centerY: number;
  scale: number;
}

// нова роль того, кому її щойно змінили. Ходить лише в його бік
export interface RoleChangedMessage {
  role: BoardRole;
}

// хто зараз друкує в обʼєкті. Поки замок тримає хтось інший, решта в цей
// обʼєкт не заходить — двоє одночасно набрали б у нього текст, і зберігся б
// лише останній. Замок ефемерний, як і решта присутності: зник сокет — зник
// і він, окремого таймауту не треба
export interface LockMessage {
  objectId: string | null;
}
