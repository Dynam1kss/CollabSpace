import type { BoardRole } from './boards';

// жива синхронізація дошки поверх ws /ws/boards/:id — бінарні кадри,
// перший байт — тип, далі байти Yjs як є (сервер їх не розбирає):
//   UPDATE        [0][yjs update]           редактор → усім іншим у кімнаті
//   SYNC_REQUEST  [1][state vector]         новий клієнт → сервер додає 4 байти
//                 свого id і шле найстаршому редактору: [1][id][state vector]
//   SYNC_REPLY    [2][id][yjs update]       редактор → сервер знімає id і
//                 віддає [2][yjs update] тому, хто питав; [2] без тіла —
//                 відповідь самого сервера «живих редакторів нема»
// без запиту/відповіді новий клієнт не зміг би застосувати наступні
// оновлення інших: yjs вимагає всю попередню історію їхніх правок — дельта з
// прогалиною в клоках лягає в pendingStructs, а delete set із неї застосується
// одразу, і обʼєкт зникне в того, хто історії не отримав. Тому відповідь
// приходить завжди, навіть порожня: клієнт по ній розуміє, що документ цілий
//
// присутність (хто зараз на дошці) — окремий канал у тому самому сокеті:
//   ROSTER    [3][json RosterMessage]   сервер → новачку, повний список
//   JOIN      [4][json PresenceMember]  сервер → решті, коли хтось зайшов
//   LEAVE     [5][json LeaveMessage]    сервер → решті, коли хтось вийшов
//   CURSOR    [6][x:f32][y:f32]         клієнт → серверу; той дописує 4 байти
//             clientId і шле решті: [6][clientId:u32][x:f32][y:f32]
//   SELECTION [7][json string[]]        клієнт → серверу; той так само дописує
//             clientId: [7][clientId:u32][json string[]]
//   LOCK      [8][json LockMessage]      клієнт → серверу; той дописує clientId:
//             [8][clientId:u32][json LockMessage]. Одне повідомлення на обидві
//             події: objectId — зайняв, null — відпустив. Двох типів тут не
//             треба, бо людина редагує щонайбільше один обʼєкт за раз, і
//             «зайняв інший» — це та сама подія, що «відпустив попередній»
//   VIEWPORT  [9][json ViewportMessage]  клієнт → серверу; той дописує clientId:
//             [9][clientId:u32][json ViewportMessage]. Шлють лише ті, хто
//             зайшов з тача: у них курсора нема, замість нього — видиме вікно
//   CHAT      [10][json ChatSendMessage] клієнт → серверу: самий лише текст.
//             Сервер пише його в базу і розсилає ВСІМ у кімнаті, включно з
//             відправником: [10][json ChatMessageInfo]. Два відступи від
//             решти каналу: цей кадр сервер не ретранслює, а зберігає, і він
//             єдиний вертається відправнику — id і час призначає база, тому
//             клієнту нема чого їх вигадувати й потім звіряти
//   ROLE      [11][json RoleChangedMessage] сервер → ОДНОМУ клієнту, якому
//             власник щойно змінив роль. Перший кадр, адресований конкретному
//             сокету, а не кімнаті: решті ця подія ні до чого. Сокет кешує
//             роль з моменту підключення, тож без цього кадру знижений
//             редактор до перезаходу і далі слав би UPDATE
//   KICKED    [12] без тіла             сервер → ОДНОМУ клієнту, якого щойно
//             прибрали з дошки; одразу по ньому сервер закриває сокет.
//             Тіла нема — казати тут нічого, сам факт і є повідомлення
//   VOICE_STATE  [13][json VoiceStateMessage] клієнт → серверу «я в розмові
//             / я вийшов»; сервер дописує clientId і шле решті:
//             [13][clientId:u32][json]. Тому, хто щойно зайшов, сервер ще й
//             переспівує по такому ж кадру на кожного, хто вже в розмові —
//             так новачок дізнається склад, не питаючи окремо
//   VOICE_SDP    [14][clientId:u32][json VoiceSdpMessage]
//   VOICE_ICE    [15][clientId:u32][json VoiceIceMessage]
//             адресні кадри переговорів, як SYNC_REQUEST: клієнт кладе туди
//             clientId ТОГО, КОМУ шле, сервер міняє його на clientId
//             відправника й передає адресату. У тіло не заглядає
//   SEAT      [16][json SeatPosition]   клієнт → серверу, той дописує
//             clientId: [16][clientId:u32][json]. Де людина «сидить» на
//             дошці. Сама позиція зберігається в базі окремим rest-запитом —
//             тут лише живе перетягування, як і в решти присутності
//   FORCE_MUTE   [17][json ForceVoiceMessage]
//   FORCE_DEAFEN [18][json ForceVoiceMessage]
//             сервер → УСІМ у кімнаті: адміністратор примусово вимкнув
//             комусь мікрофон або звук. Усім — бо решта має бачити замочок
//             на тій людині; сам адресат ще й виконує. Стан живе на сервері
//             й переживає перезавантаження сторінки: інакше примусовий мьют
//             знімався б простим F5
//   SHOW_VIEW [19][json ShowViewMessage] клієнт → серверу, той дописує
//             clientId: [19][clientId:u32][json]. «Подивіться, де я» —
//             одноразовий кадр по натисканню, після якого камера решти
//             переїжджає в мою. Не VIEWPORT: той шлють безперервно і лише з
//             тача, як заміну курсора, і його ніхто не застосовує до своєї
//             камери. Роллю не гейтимо — чужа камера не є вмістом дошки,
//             так само як і виділення.
//             У тілі — ТОЧКА ДОШКИ, яка в мене посеред екрана, а не мій
//             екранний зсув: зсув має сенс лише разом із моїм розміром
//             вікна, і в того, хто дивиться з іншого екрана, вміст від
//             нього виїжджав у куток
// Хто в кімнаті — знає сам сервер, тому роздає це він, а не клієнти
// здогадуються з чужого трафіку. Присутність ефемерна: у Y.Doc і в базу не
// потрапляє, з розривом сокета просто зникає. Глядач присутній нарівні з
// усіма — його курсор і виділення ходять як у решти; за роллю гейтяться
// тільки UPDATE і LOCK, тобто те, що міняє вміст або заважає іншим.
// Json скрізь, крім курсора: решта кадрів рідкі (вхід, вихід, список,
// зміна виділення), і читати їх очима в devtools дорожче, ніж кілька байтів.
// Курсор іде десятками за секунду, тому бінарний і фіксованої довжини.
// Втрата чи запізнення кадру присутності нічого не ламає: наступний перекриє,
// максимум курсор трохи відстане — ні підтверджень, ні порядку тут не треба
