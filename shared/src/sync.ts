import type { BoardRole } from './boards';

// жива синхронізація дошки поверх ws /ws/boards/:id — бінарні кадри,
// перший байт — тип, далі байти Yjs як є (сервер їх не розбирає):
//   UPDATE        [0][yjs update]           редактор → усім іншим у кімнаті
//   SYNC_REQUEST  [1][state vector]         новий клієнт → сервер додає 4 байти
//                 свого id і шле найстаршому редактору: [1][id][state vector]
//   SYNC_REPLY    [2][id][yjs update]       редактор → сервер знімає id і
//                 віддає [2][yjs update] тому, хто питав; [2] без тіла —
//                 відповідь самого сервера «живих редакторів нема»
// без запиту/відповіді новий клієнт не зміг би застосувати наступні
// оновлення інших: yjs вимагає всю попередню історію їхніх правок — дельта з
// прогалиною в клоках лягає в pendingStructs, а delete set із неї застосується
// одразу, і обʼєкт зникне в того, хто історії не отримав. Тому відповідь
// приходить завжди, навіть порожня: клієнт по ній розуміє, що документ цілий
//
// присутність (хто зараз на дошці) — окремий канал у тому самому сокеті:
//   ROSTER    [3][json RosterMessage]   сервер → новачку, повний список
//   JOIN      [4][json PresenceMember]  сервер → решті, коли хтось зайшов
//   LEAVE     [5][json LeaveMessage]    сервер → решті, коли хтось вийшов
//   CURSOR    [6][x:f32][y:f32]         клієнт → серверу; той дописує 4 байти
//             clientId і шле решті: [6][clientId:u32][x:f32][y:f32]
//   SELECTION [7][json string[]]        клієнт → серверу; той так само дописує
//             clientId: [7][clientId:u32][json string[]]
// Хто в кімнаті — знає сам сервер, тому роздає це він, а не клієнти
// здогадуються з чужого трафіку. Присутність ефемерна: у Y.Doc і в базу не
// потрапляє, з розривом сокета просто зникає. Роль тут не обмежує нічого —
// глядач так само присутній; за роллю гейтиться лише UPDATE.
// Json скрізь, крім курсора: решта кадрів рідкі (вхід, вихід, список,
// зміна виділення), і читати їх очима в devtools дорожче, ніж кілька байтів.
// Курсор іде десятками за секунду, тому бінарний і фіксованої довжини.
// Втрата чи запізнення кадру присутності нічого не ламає: наступний перекриє,
// максимум курсор трохи відстане — ні підтверджень, ні порядку тут не треба
export const SYNC_MSG = {
  UPDATE: 0,
  SYNC_REQUEST: 1,
  SYNC_REPLY: 2,
  ROSTER: 3,
  JOIN: 4,
  LEAVE: 5,
  CURSOR: 6,
  SELECTION: 7,
} as const;

export const SYNC_REQUESTER_ID_BYTES = 4;

// [clientId:u32][x:f32][y:f32] — координати дошки, не екрана: у кожного свій
// зсув і масштаб, тому переводить їх той, хто малює
export const CURSOR_BYTES = 12;

// id сокета, не користувача: та сама людина з двох вкладок — два записи,
// і кожен зникає окремо
export interface PresenceMember {
  clientId: number;
  userId: string;
  displayName: string;
  role: 'OWNER' | BoardRole;
}

export interface RosterMessage {
  // який із members — це я; себе в списку присутніх не показуємо
  you: number;
  members: PresenceMember[];
}

export interface LeaveMessage {
  clientId: number;
}
